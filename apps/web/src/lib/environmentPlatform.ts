/**
 * Map an environment's reported OS to the `navigator.platform` string the
 * path helpers expect, falling back to the local platform when unknown.
 */
export function getEnvironmentBrowsePlatform(os: string | null | undefined): string {
  if (os === "windows") {
    return "Win32";
  }
  if (os === "darwin") {
    return "MacIntel";
  }
  if (os === "linux") {
    return "Linux";
  }
  return typeof navigator === "undefined" ? "" : navigator.platform;
}
